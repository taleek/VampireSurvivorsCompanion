// Build a map: lowercase-no-extension -> full path
export const iconMap = {};
for (const file of iconFiles) {
  const dot = file.lastIndexOf(".");
  const key = file.slice(0, dot).toLowerCase();
  // Only set if not already set (first entry wins — .webp listed before .png where both exist)
  if (!iconMap[key]) {
    iconMap[key] = `/icons/${file}`;
  }
}

/**
 * Resolve an icon path from an item name or existing img path.
 * Strips any existing extension/prefix so data files can use any format.
 */
export function resolveIcon(nameOrPath) {
  if (!nameOrPath) return null;
  let base = nameOrPath.replace(/^\/icons\//, "");
  const dot = base.lastIndexOf(".");
  if (dot !== -1) base = base.slice(0, dot);
  return iconMap[base.toLowerCase()] ?? null;
}
